"""Read G-code written by Creality Print: header figures, per-layer toolpaths,
and a check that the G-code uses the settings the project asked for."""
import math
import re

_NUM = re.compile(r"([XYZEIJFS])(-?\d*\.?\d+)")


def _words(line):
    return {k: float(v) for k, v in _NUM.findall(line.split(";", 1)[0])}


def read_header(path):
    """Figures from the header and the start of the file, plus a few counts."""
    info = {"time_s": None, "filament_m": None, "layers": None, "max_z_mm": None, "generator": None,
            "nozzle_first_c": None, "nozzle_other_c": None, "bed_c": None, "layer_heights": {},
            "types": {}}
    layer = 0
    with open(path, errors="replace") as f:
        for line in f:
            if line.startswith(";TIME:") and info["time_s"] is None:
                info["time_s"] = float(line[6:])
            elif line.startswith(";Filament used:") and info["filament_m"] is None:
                info["filament_m"] = float(line.split(":", 1)[1].strip().rstrip("m"))
            elif line.startswith("; total layer number:"):
                info["layers"] = int(line.split(":", 1)[1])
            elif line.startswith("; max_z_height:"):
                info["max_z_mm"] = float(line.split(":", 1)[1])
            elif line.startswith("; generated by"):
                info["generator"] = line[2:].split(" on ")[0].replace("generated by ", "").strip()
            elif line.startswith(";LAYER_CHANGE"):
                layer += 1
            elif line.startswith(";HEIGHT:"):
                h = round(float(line[8:]), 2)
                info["layer_heights"][h] = info["layer_heights"].get(h, 0) + 1
            elif line.startswith(";TYPE:"):
                t = line[6:].strip()
                info["types"][t] = info["types"].get(t, 0) + 1
            elif line.startswith(("M109 ", "M104 ")):
                s = _words(line).get("S")
                if s is None or s == 0:
                    continue
                if layer <= 1 and info["nozzle_first_c"] is None:
                    info["nozzle_first_c"] = s
                elif layer >= 2 and info["nozzle_other_c"] is None:
                    info["nozzle_other_c"] = s
            elif line.startswith(("M190 ", "M140 ")) and info["bed_c"] is None:
                s = _words(line).get("S")
                if s:
                    info["bed_c"] = s
    if info["nozzle_other_c"] is None:
        info["nozzle_other_c"] = info["nozzle_first_c"]
    return info


def _arc(x0, y0, w, clockwise):
    """Points along a G2/G3 arc (I/J centre offsets), excluding the start point."""
    x1, y1 = w.get("X", x0), w.get("Y", y0)
    cx, cy = x0 + w.get("I", 0.0), y0 + w.get("J", 0.0)
    r = math.hypot(x0 - cx, y0 - cy)
    a0, a1 = math.atan2(y0 - cy, x0 - cx), math.atan2(y1 - cy, x1 - cx)
    sweep = a1 - a0
    if clockwise and sweep >= 0:
        sweep -= 2 * math.pi
    elif not clockwise and sweep <= 0:
        sweep += 2 * math.pi
    n = max(2, min(64, int(abs(sweep) * r / 0.5)))
    pts = [(cx + r * math.cos(a0 + sweep * k / n), cy + r * math.sin(a0 + sweep * k / n)) for k in range(1, n)]
    return pts + [(x1, y1)]


def parse_layers(path):
    """Per-layer extrusion paths: [{"z", "height", "paths": {type: [[x0,y0,x1,y1,...], ...]}}].

    Coordinates are rounded to 0.01 mm. Travel moves split paths. Extrusion
    is taken as relative (M83), which is what Creality Print writes.
    """
    layers, cur = [], None
    x = y = 0.0
    typ, poly = "Custom", None
    relative_e = True

    def close():
        nonlocal poly
        if poly is not None and len(poly) >= 4 and cur is not None:
            cur["paths"].setdefault(typ, []).append(poly)
        poly = None

    with open(path, errors="replace") as f:
        for line in f:
            c = line[:1]
            if c == ";":
                if line.startswith(";LAYER_CHANGE"):
                    close()
                    cur = {"z": None, "height": None, "paths": {}}
                    layers.append(cur)
                elif line.startswith(";Z:") and cur is not None and cur["z"] is None:
                    cur["z"] = float(line[3:])
                elif line.startswith(";HEIGHT:") and cur is not None and cur["height"] is None:
                    cur["height"] = float(line[8:])
                elif line.startswith(";TYPE:"):
                    close()
                    typ = line[6:].strip()
                continue
            if c != "G" and c != "M":
                continue
            head = line.split(None, 1)[0] if line.strip() else ""
            if head == "M83":
                relative_e = True
            elif head == "M82":
                relative_e = False
            if head not in ("G0", "G1", "G2", "G3"):
                continue
            w = _words(line)
            nx, ny = w.get("X", x), w.get("Y", y)
            extruding = relative_e and w.get("E", 0.0) > 0 and (nx != x or ny != y)
            if extruding and cur is not None:
                if poly is None:
                    poly = [round(x, 2), round(y, 2)]
                pts = _arc(x, y, w, head == "G2") if head in ("G2", "G3") else [(nx, ny)]
                for px, py in pts:
                    poly += [round(px, 2), round(py, 2)]
            elif nx != x or ny != y:
                close()
            x, y = nx, ny
    close()
    return layers


def check_settings(header, expected):
    """Compare the G-code with the settings the project asked for.

    expected: {"layer_height", "first_layer_height", "nozzle_first_c", "nozzle_other_c", "bed_c",
               "support"} -> list of {"ok": bool, "text": str}
    """
    out = []
    hs = {h: n for h, n in header["layer_heights"].items() if n}
    lh = expected.get("layer_height")
    if lh is not None and hs:
        main = max(hs, key=hs.get)
        total = sum(hs.values())
        share = hs[main] / total
        ok = abs(main - lh) < 0.006
        detail = f"{share:.0%} of {total} layers" if share < 0.97 else f"all {total} layers" if share == 1 \
            else f"{hs[main]} of {total} layers"
        out.append({"ok": ok, "text": f"Layer height {main:g} mm on {detail}"
                    + ("" if ok else f" (asked for {lh:g} mm)")})
        odd = sorted(h for h in hs if abs(h - lh) > 0.006 and abs(h - expected.get("first_layer_height", -1)) > 0.006)
        if odd and any(h < lh / 2 for h in odd):
            out.append({"ok": False, "text": "Some layers are much thinner (" + ", ".join(f"{h:g}" for h in odd[:4])
                        + " mm), usually support layers on their own heights"})
    for key, label in (("nozzle_first_c", "Nozzle, first layer"), ("nozzle_other_c", "Nozzle, other layers"),
                       ("bed_c", "Bed")):
        want, got = expected.get(key), header.get(key)
        if want is None or got is None:
            continue
        ok = abs(float(want) - float(got)) < 0.5
        out.append({"ok": ok, "text": f"{label} {got:g} °C" + ("" if ok else f" (asked for {float(want):g} °C)")})
    if expected.get("support") is not None:
        has = any(t.startswith("Support") for t in header["types"])
        if expected["support"]:
            out.append({"ok": has, "text": "Supports are printed" if has else "Supports are on but none were generated"})
        elif has:
            out.append({"ok": False, "text": "Supports were generated although they are off"})
    return out
